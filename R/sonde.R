# Sonde data helpers
#
# apply_corrections() is the declarative correction layer from the OGFL sonde
# pipeline (Water_data/OGFL/Sonde_data/scripts/apply_corrections.R): the sonde
# master holds the raw values as they came off the instruments, and every fix
# is one row in a corrections CSV, applied in memory at time of use.
# load_sonde_master() reads a master CSV, applies the corrections, and adds a
# POSIXct `datetime` key for joining to field sheet sonde times.
#
# Corrections file columns:
#   unit_id         e.g. ProDSS2  (matches the unit_id assigned in the main
#                   script via str_extract(path, "ProDSS\\d+"))
#   field           the wide column to change: a sensor (ph, temp, cond, lat,
#                   ...) OR "datetime" to move the row's timestamp.
#   start_datetime  "YYYY-MM-DD HH:MM:SS"  (inclusive) -- match window start
#   end_datetime    "YYYY-MM-DD HH:MM:SS"  (inclusive) -- match window end
#                   (start == end for a single-reading point edit)
#   original_value  optional guard: only change cells currently equal to this
#                   (numeric compared with tolerance). Blank = change all in
#                   the window. Records what was there (sentinels store the 0/
#                   99.99). Ignored for field = datetime (the window is the key).
#   new_value       the value to write. Blank or "NA" -> NA (a null). For
#                   field = datetime, a full "YYYY-MM-DD HH:MM:SS".
#   reason          free text -- the WHY (this is your audit record)
#   author          who logged it
#   date_logged     YYYY-MM-DD
#   origin          "manual" (hand-curated) or "sentinel" (auto-generated by
#                   sync_sentinel_corrections() in the Sonde_data scripts;
#                   sentinel rows are regenerated each run, manual rows kept).
#
# datetime edits run FIRST (they move the matching key), then the timestamp
# index is rebuilt, then value edits apply.

apply_corrections <- function(df,
                              corrections_path = "corrections/data_corrections.csv",
                              date_col = "date", time_col = "time",
                              unit_col = "unit_id", origins = NULL, verbose = TRUE) {
  # origins = NULL applies ALL rows (consumers: full clean -- sentinel decoding
  # plus manual corrections). The master-building scripts apply NOTHING (the
  # master is the raw record); the origins filter remains for ad-hoc use, e.g.
  # origins = "sentinel" to decode only the instrument no-reading codes.

  if (!file.exists(corrections_path)) {
    warning("apply_corrections: no file at '", corrections_path, "' -- df returned unchanged.")
    return(df)
  }

  corr <- utils::read.csv(corrections_path, stringsAsFactors = FALSE,
                          strip.white = TRUE, comment.char = "#")
  corr <- corr[!is.na(corr$unit_id) & nzchar(trimws(corr$unit_id)), , drop = FALSE]
  if (nrow(corr) == 0L) return(df)

  need <- c("unit_id", "field", "start_datetime", "end_datetime", "new_value")
  miss <- setdiff(need, names(corr))
  if (length(miss))
    stop("apply_corrections: corrections file missing column(s): ", paste(miss, collapse = ", "),
         ". Expected the field/new_value schema.")
  if (!"original_value" %in% names(corr)) corr$original_value <- NA_character_

  for (req in c(date_col, time_col, unit_col)) {
    if (!req %in% names(df))
      stop("apply_corrections: expected column '", req, "' not found in df.")
  }

  # blank = empty / whitespace / the literal "NA" (robust to write.csv and hand edits)
  blank <- function(x) is.na(x) | !nzchar(trimws(x)) | toupper(trimws(x)) == "NA"

  # One POSIXct timestamp per row of df, built from its date + time columns.
  # `date` is a Date and `time` a chron 'times' (or character) in this pipeline;
  # format() renders both to plain strings so paste() is encoding-safe.
  row_dt <- as.POSIXct(paste(as.character(df[[date_col]]), format(df[[time_col]])),
                       format = "%Y-%m-%d %H:%M:%S", tz = "UTC")
  corr$.start <- as.POSIXct(corr$start_datetime, format = "%Y-%m-%d %H:%M:%S", tz = "UTC")
  corr$.end   <- as.POSIXct(corr$end_datetime,   format = "%Y-%m-%d %H:%M:%S", tz = "UTC")

  # Sentinel rows (origin == "sentinel") are auto-generated and may number in
  # the thousands, so they are summarised, not logged per row. Manual rows are
  # logged individually. Missing/blank origin counts as manual.
  origin <- if ("origin" %in% names(corr)) tolower(trimws(corr$origin)) else rep("manual", nrow(corr))
  origin[blank(origin)] <- "manual"

  # Optional origin filter: NULL = apply everything; otherwise only these origins.
  apply_k <- if (is.null(origins)) rep(TRUE, nrow(corr)) else origin %in% tolower(origins)
  if (!any(apply_k)) return(df)

  field_lc <- tolower(trimws(corr$field))
  is_ts <- field_lc %in% c("datetime", "date_time", "timestamp")

  match_rows <- function(k) {           # rows of this unit within [start, end]
    h <- df[[unit_col]] == corr$unit_id[k] & !is.na(row_dt) &
         row_dt >= corr$.start[k] & row_dt <= corr$.end[k]
    h[is.na(h)] <- FALSE
    h
  }

  # --- PASS 1: timestamp edits (field = datetime) -----------------------------
  # The timestamp lives in three derived columns (date/time/date_time), and it
  # is also the key everything else matches on, so these run FIRST and the index
  # is rebuilt afterwards. new_value is a full "YYYY-MM-DD HH:MM:SS".
  n_ts <- 0L
  for (k in which(is_ts & apply_k)) {
    if (is.na(corr$.start[k]) || is.na(corr$.end[k])) {
      warning(sprintf("rule %d (datetime): unparseable start/end -- skipped", k)); next
    }
    new_ts <- as.POSIXct(trimws(corr$new_value[k]), format = "%Y-%m-%d %H:%M:%S", tz = "UTC")
    if (is.na(new_ts)) {
      warning(sprintf("rule %d (datetime): unparseable new_value '%s' -- skipped", k, corr$new_value[k])); next
    }
    hit <- match_rows(k)
    if (!any(hit)) {
      if (verbose) message(sprintf("  [datetime %d] no %s row in %s..%s -- nothing to move",
                                   k, corr$unit_id[k], corr$start_datetime[k], corr$end_datetime[k]))
      next
    }
    if (sum(hit) > 1)
      warning(sprintf("rule %d (datetime): matched %d rows, all set to %s (collision?)",
                      k, sum(hit), corr$new_value[k]))
    df[[date_col]][hit] <- as.Date(format(new_ts, "%Y-%m-%d", tz = "UTC"))
    df[[time_col]][hit] <- chron::chron(times = format(new_ts, "%H:%M:%S", tz = "UTC"))
    if ("date_time" %in% names(df))
      df$date_time[hit] <- paste(as.character(df[[date_col]][hit]), format(df[[time_col]][hit]), sep = "_")
    n_ts <- n_ts + sum(hit)
    if (verbose)
      message(sprintf("  [datetime %d] %s  %s -> %s  (%d row) | %s", k, corr$unit_id[k],
                      corr$start_datetime[k], corr$new_value[k], sum(hit), corr$reason[k]))
  }
  if (n_ts > 0L)
    row_dt <- as.POSIXct(paste(as.character(df[[date_col]]), format(df[[time_col]])),
                         format = "%Y-%m-%d %H:%M:%S", tz = "UTC")

  # --- PASS 2: value edits (set `field` to `new_value` over the window) --------
  # Optional original_value guard: only change cells currently equal to it
  # (numeric compared with tolerance, so float precision doesn't cause misses).
  # Blank/NA new_value means set to NA (the old "null").
  sent_changed <- 0L
  for (k in which(!is_ts & apply_k)) {
    field <- trimws(corr$field[k])
    if (!field %in% names(df)) {
      if (verbose && origin[k] != "sentinel")
        message(sprintf("  [skip] rule %d: field '%s' is not a column here", k, field))
      next
    }
    if (is.na(corr$.start[k]) || is.na(corr$.end[k])) {
      warning(sprintf("rule %d: unparseable start/end datetime -- skipped", k)); next
    }

    hit <- match_rows(k)

    if (!blank(corr$original_value[k])) {
      col <- df[[field]]; ov <- trimws(corr$original_value[k])
      if (is.numeric(col)) {
        ovn   <- suppressWarnings(as.numeric(ov))
        guard <- !is.na(col) & !is.na(ovn) & abs(col - ovn) < 1e-6
      } else {
        guard <- !is.na(col) & as.character(col) == ov
      }
      hit <- hit & guard
    }

    if (blank(corr$new_value[k])) {
      newval <- NA
    } else if (is.numeric(df[[field]])) {
      newval <- suppressWarnings(as.numeric(trimws(corr$new_value[k])))
    } else {
      newval <- trimws(corr$new_value[k])
    }
    df[[field]][hit] <- newval

    if (origin[k] == "sentinel") {
      sent_changed <- sent_changed + sum(hit)
    } else if (verbose) {
      message(sprintf("  [rule %d] %s / %s  %s..%s  -> set %d value(s) to %s | %s",
                      k, corr$unit_id[k], field, corr$start_datetime[k], corr$end_datetime[k],
                      sum(hit), if (is.na(newval)) "NA" else as.character(newval), corr$reason[k]))
    }
  }

  if (verbose && any(origin == "sentinel"))
    message(sprintf("  [sentinel] %d rule(s) -> set %d value(s) to NA total",
                    sum(origin == "sentinel"), sent_changed))

  df
}

# Read a sonde master CSV, apply the corrections file, and add `datetime`.
#
# Corrections run BEFORE `datetime` is derived because a `field = datetime`
# correction shifts a row's date/time (used to disambiguate two units that
# logged the same second), so the join key is built from the corrected
# timestamp. `date` is converted to Date and `time` to chron 'times' first:
# that is what apply_corrections() writes back for retimed rows, and plain
# character columns would silently coerce those values to numbers.
#
# master_path      path to sonde_data_master_<date>.csv
# corrections_path path to data_corrections.csv (NULL = no corrections)
# verbose          passed to apply_corrections()
load_sonde_master <- function(master_path, corrections_path = NULL, verbose = TRUE) {
  df <- utils::read.csv(master_path)
  df$date <- as.Date(df$date)
  df$time <- chron::chron(times = df$time)
  if (!is.null(corrections_path))
    df <- apply_corrections(df, corrections_path = corrections_path,
                            date_col = 'date', time_col = 'time',
                            unit_col = 'unit_id', verbose = verbose)
  df$datetime <- as.POSIXct(paste(df$date, format(df$time)),
                            format = '%Y-%m-%d %H:%M:%S', tz = 'UTC')
  df
}
